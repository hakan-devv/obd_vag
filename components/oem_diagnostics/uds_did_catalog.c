static uint16_t read_u16_be(const uint8_t *p)
{
    return (uint16_t)(((uint16_t)p[0] << 8U) | p[1]);
}

static uint16_t read_u16_le(const uint8_t *p)
{
    return (uint16_t)(((uint16_t)p[1] << 8U) | p[0]);
}

bool uds_did_catalog_decode(const uds_did_descriptor_t *descriptor,
                            const uint8_t *data, size_t length, double *value)
{
    if (descriptor == NULL || data == NULL || value == NULL ||
        length < descriptor->min_length || length > descriptor->max_length ||
        descriptor->decode_kind == UDS_DID_DECODE_RAW ||
        descriptor->decode_kind == UDS_DID_DECODE_ASCII) {
        return false;
    }
    const size_t width = (descriptor->decode_kind == UDS_DID_DECODE_U8 ||
                          descriptor->decode_kind == UDS_DID_DECODE_S8) ? 1U :
                         (descriptor->decode_kind == UDS_DID_DECODE_U32_BE ||
                          descriptor->decode_kind == UDS_DID_DECODE_S32_BE) ? 4U : 2U;
    if ((size_t)descriptor->data_offset + width > length) return false;
    const uint8_t *p = &data[descriptor->data_offset];
    double raw = 0.0;
    switch (descriptor->decode_kind) {
    case UDS_DID_DECODE_U8: raw = p[0]; break;
    case UDS_DID_DECODE_S8: raw = (int8_t)p[0]; break;
    case UDS_DID_DECODE_U16_BE: raw = read_u16_be(p); break;
    case UDS_DID_DECODE_S16_BE: raw = (int16_t)read_u16_be(p); break;
    case UDS_DID_DECODE_U16_LE: raw = read_u16_le(p); break;
    case UDS_DID_DECODE_S16_LE: raw = (int16_t)read_u16_le(p); break;
    case UDS_DID_DECODE_U32_BE:
        raw = (double)(((uint32_t)p[0] << 24U) | ((uint32_t)p[1] << 16U) |
                       ((uint32_t)p[2] << 8U) | p[3]);
        break;
    case UDS_DID_DECODE_S32_BE:
        raw = (double)(int32_t)(((uint32_t)p[0] << 24U) | ((uint32_t)p[1] << 16U) |
                                ((uint32_t)p[2] << 8U) | p[3]);
        break;
    default: return false;
    }
    const double decoded = raw * descriptor->scale + descriptor->offset;
    if (descriptor->has_engineering_range &&
        (decoded < descriptor->engineering_min || decoded > descriptor->engineering_max)) {
        return false;
    }
    *value = decoded;
    return true;
}

bool uds_did_catalog_is_query_allowed(uint16_t did,
                                      diag_ecu_role_t role,
                                      const char *profile_id,
                                      bool session_ready,
                                      bool allow_experimental,
                                      bool manual_probe)
{
    const size_t count = sizeof(s_catalog) / sizeof(s_catalog[0]);
    for (size_t i = 0U; i < count; ++i) {
        const uds_did_descriptor_t *descriptor = &s_catalog[i];
        if (descriptor->did != did || descriptor->role != role) continue;
        if (manual_probe) {
            if (!descriptor->manual_probe_allowed) continue;
        } else if (!descriptor->auto_query_allowed) {
            continue;
        }
        if (!allow_experimental &&
            descriptor->validation < UDS_DID_VALIDATION_SOURCE_BACKED) continue;
        if (descriptor->session_required && !session_ready) continue;
        if (profile_id != NULL && profile_id[0] != '\0' &&
            descriptor->profile_id != NULL && descriptor->profile_id[0] != '\0' &&
            strcmp(descriptor->profile_id, profile_id) != 0) continue;
        return true;
    }
    return false;
}
